"""Stable per-boot node identity and monotonic uptime facts.

Read-only, best-effort, Linux-first. Every reader here returns ``None``
rather than fabricating a value from this process's PID or the wall clock
when the real platform fact is unavailable -- a Camera Node running on a
non-Linux host (or under a test that never runs on a real Linux kernel)
still starts and serves traffic; boot identity simply degrades to ``None``
rather than blocking startup or lying about it. See "Stable boot identity"
in docs/camera-node-installer-design.md.
"""

from __future__ import annotations

from pathlib import Path
import time
from typing import Callable


#: The kernel's own per-boot random UUID -- regenerated by the kernel itself
#: on every real boot, stable for the machine's entire uptime, and never
#: derived from this (or any) process. This is the preferred Linux reference
#: implementation named by the milestone brief.
BOOT_ID_PATH = Path("/proc/sys/kernel/random/boot_id")
UPTIME_PATH = Path("/proc/uptime")
_MAX_BOOT_ID_LENGTH = 64
_BOOT_ID_CHARACTERS = frozenset("0123456789abcdef-")


def read_boot_id(*, path: Path = BOOT_ID_PATH) -> str | None:
    """Read the kernel-assigned boot ID. ``None`` on any platform,
    permission, or format problem -- a missing boot identity degrades this
    Node's own diagnostics; it must never crash startup or synthesize a
    value from the PID or wall clock (explicitly excluded by the milestone
    brief)."""

    try:
        raw = path.read_text(encoding="ascii").strip().lower()
    except (OSError, UnicodeDecodeError):
        return None
    if not raw or len(raw) > _MAX_BOOT_ID_LENGTH:
        return None
    if any(character not in _BOOT_ID_CHARACTERS for character in raw):
        return None
    return raw


def read_os_uptime_seconds(*, path: Path = UPTIME_PATH) -> float | None:
    """Machine/OS uptime read from the kernel itself (`/proc/uptime`'s
    first field) -- resets only on a real reboot, unaffected by this
    process's own restart. Distinct from `ServiceClock.uptime_seconds`
    below, which measures only how long *this Camera Node process* has
    been running; a service restart with no machine reboot changes one and
    not the other, which is exactly the distinction the host needs to tell
    a process crash apart from a real reboot."""

    try:
        raw = path.read_text(encoding="ascii")
    except (OSError, UnicodeDecodeError):
        return None
    fields = raw.split()
    if not fields:
        return None
    try:
        seconds = float(fields[0])
    except ValueError:
        return None
    return seconds if seconds >= 0 else None


class ServiceClock:
    """This process's own uptime, from a monotonic source only -- never
    wall-clock time, which an NTP correction or manual clock change could
    move backwards or forwards. A fresh instance's `uptime_seconds()`
    starts at (approximately) zero and only ever grows until the process
    itself restarts, independent of machine/OS uptime."""

    def __init__(self, *, monotonic: Callable[[], float] = time.monotonic) -> None:
        self._monotonic = monotonic
        self._started_at_monotonic = monotonic()

    def uptime_seconds(self) -> float:
        return max(0.0, self._monotonic() - self._started_at_monotonic)


def resolve_service_version() -> str:
    """The installed Camera Node package version.

    A real installed Node (via `scripts/install_camera_node.py`) always has
    proper wheel `.dist-info` metadata -- `importlib.metadata` resolves it
    directly. A development checkout importing `mockingbird_node` without
    ever installing the separate slim wheel (every test in this repository)
    has no such metadata; `__version__` below is the honest fallback for
    that case only. Never raises.
    """

    from importlib import metadata

    for distribution_name in ("mockingbird-camera-node", "mockingbird_camera_node"):
        try:
            return metadata.version(distribution_name)
        except metadata.PackageNotFoundError:
            continue
    from . import __version__

    return __version__
